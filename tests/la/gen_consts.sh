#!/bin/sh
# tests/la/gen_consts.sh -- write the C header sea_consts.h from Sea's contract files (POSIX sh +
# awk; macOS and Linux). docs/DESIGN.md 2.13.8, lead decision L-jd.
#
# usage: sh tests/la/gen_consts.sh OUT_FILE
#   OUT_FILE  the header to write (the Makefile writes BUILD/obj/la/sea_consts.h; the cross run a
#             file in its temporary directory); its directory must exist
#
# The include files are found relative to this script (../../include), so the script works
# unchanged inside the x86_64-linux bundle, as Baysick's tests/kern/kern_run.sh derives
# runtime_consts.h from include/runtime.inc. The header names no value of its own:
#
#   * every line `.equiv SEA_<NAME>, <value>` of include/rt.inc and include/limits.inc whose value
#     is a decimal or hexadecimal literal (optionally negative) becomes `#define SEA_<NAME> <value>`
#     (a negative value parenthesized); lines inside macro bodies (`.equiv SEA_ENT_\name, \id`) are
#     not literals and are skipped;
#   * every record `\m <code>, <NAME>, ...` of include/errors.inc's SEA_ERROR_LIST becomes
#     `#define SEA_E_<NAME> <code>`.
#
# tests/la/la_check.c takes SEA_LA_NB, SEA_VAR_*, the error codes and the site layout
# (SEA_SITE_FILE, SEA_SITE_LINE, SEA_SITE_SIZE) and the object layouts from it. The file is written
# to a temporary name beside OUT_FILE and renamed, so a failed run leaves no partial header.
#
# Exit status: 0 written; 2 setup error (usage, a missing include file, a name la_check.c needs
# missing from the contract files, a write failure).

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
if [ $# -ne 1 ]; then
    echo "gen_consts.sh: usage: sh tests/la/gen_consts.sh OUT_FILE" >&2
    exit 2
fi
OUT=$1
INC=$ROOT/include
for f in rt.inc limits.inc errors.inc; do
    [ -f "$INC/$f" ] || { echo "gen_consts.sh: $INC/$f not found" >&2; exit 2; }
done
OUTDIR=$(dirname "$OUT")
[ -d "$OUTDIR" ] || { echo "gen_consts.sh: directory '$OUTDIR' does not exist" >&2; exit 2; }
TMPF=$OUT.tmp.$$
trap 'rm -f "$TMPF"' EXIT
trap 'rm -f "$TMPF"; exit 2' HUP INT TERM PIPE

{
    echo "/* sea_consts.h -- generated by tests/la/gen_consts.sh from include/rt.inc, include/limits.inc"
    echo "   and include/errors.inc (DESIGN.md 2.13.8, L-jd). Do not edit: the contract files are the"
    echo "   only place these values are named. */"
    echo "#ifndef SEA_CONSTS_H"
    echo "#define SEA_CONSTS_H"
    for f in rt.inc limits.inc; do
        echo "/* $f: .equiv SEA_* */"
        awk '
        $1 == ".equiv" {
            name = $2; sub(/,$/, "", name)
            val = $3
            if (name !~ /^SEA_[A-Za-z0-9_]+$/) next
            if (val ~ /^-?[0-9]+$/ || val ~ /^0[xX][0-9A-Fa-f]+$/) {
                if (val ~ /^-/) val = "(" val ")"
                print "#define " name " " val
            }
        }' "$INC/$f"
    done
    echo "/* errors.inc: SEA_ERROR_LIST records */"
    awk '
    /^\.macro SEA_ERROR_LIST/ { inlist = 1; next }
    inlist && /^\.endm/ { inlist = 0; next }
    inlist && /^    \\m / {
        line = substr($0, 8)
        n = split(line, f, ", ")
        if (n < 2 || f[1] !~ /^[0-9]+$/ || f[2] !~ /^[A-Z0-9_]+$/) { bad = 1; next }
        print "#define SEA_E_" f[2] " " f[1]
    }
    END { if (bad) exit 1 }' "$INC/errors.inc" || { echo "gen_consts.sh: malformed SEA_ERROR_LIST record in errors.inc" >&2; exit 2; }
    echo "#endif"
} > "$TMPF" || { echo "gen_consts.sh: cannot write $TMPF" >&2; exit 2; }

# the names tests/la/la_check.c uses must be there (a renamed contract value is a setup error here,
# not a confusing compile error later)
for n in SEA_LA_NB SEA_VAR_NEON SEA_VAR_SSE2 SEA_VAR_AVX2 SEA_SITE_FILE SEA_SITE_LINE SEA_SITE_SIZE \
         SEA_E_SHAPE_MISMATCH SEA_OBJ_RC SEA_OBJ_TAG SEA_TAG_ARRAY SEA_TAG_STR SEA_RC_STATIC \
         SEA_ARR_EK SEA_ARR_RANK SEA_ARR_ROWS SEA_ARR_COLS SEA_ARR_DATA SEA_ARR_SIZE SEA_EK_F64 \
         SEA_STR_LEN SEA_STR_BYTES SEA_SHAPE_VEC; do
    grep -q "^#define $n " "$TMPF" || { echo "gen_consts.sh: $n not found in the contract files" >&2; exit 2; }
done
mv -f "$TMPF" "$OUT" || { echo "gen_consts.sh: cannot write $OUT" >&2; exit 2; }
exit 0
