sea_main:
    PROLOGUE
    leaq .Lfmod_vec_table(%rip), %rbx
    movq (%rbx), %r12               # N
    addq $8, %rbx                   # the first record
    xorl %r13d, %r13d               # record index i
1:  cmpq %r12, %r13
    jae 2f                          # every record checked
    movq 0(%rbx), %rax              # a (bits)
    movq %rax, %xmm0
    movq 8(%rbx), %rax              # b (bits)
    movq %rax, %xmm1
    call sea_fmod
    movq %xmm0, %r14                # the result's bits
    cmpq 16(%rbx), %r14
    jne 3f                          # compared as bits, never as floats
    addq $24, %rbx
    incq %r13
    jmp 1b
2:  KV "fmod vectors: ", %r12       # N read from the table
    TXT " ok\n"
    EPILOGUE
3:  KV "fmod vector ", %r13         # the first mismatch: index and bits
    TXT ": a="
    movq 0(%rbx), %rdi
    call put_hex
    TXT " b="
    movq 8(%rbx), %rdi
    call put_hex
    TXT " expected="
    movq 16(%rbx), %rdi
    call put_hex
    TXT " got="
    movq %r14, %rdi
    call put_hex
    TXT "\n"
    call sea_out_flush
    movl $1, %edi                   # status 1
    call _exit@PLT

